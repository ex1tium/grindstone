"""FF-01: the kernel module map as data, and the import contracts it implies.

The table mirrors "Module map" in the foundation's Components tab. Reading of
the dependency rule, applied strictly: `contracts`, `store` and `platform`
(the foundation and platform layers) are available to every module above
them; dependencies at the domain layer and above are exactly the ones listed.
Higher modules are reached from lower ones only through continuations or
events, never imports.

Run `python -m scripts.ff.module_map > .importlinter` after changing the
table; a test fails if the committed file differs from `render()`.
"""

KERNEL = "grindstone"
FACTORIES = ("grindstone_sdlc", "grindstone_notes")
RUNNER = "grindstone_runner"

SUBSTRATE = ("contracts", "store", "platform")

# module -> modules it may import, beyond the substrate available to it.
MODULE_MAP: dict[str, tuple[str, ...]] = {
    "contracts": (),
    "store": ("contracts",),
    "platform": ("contracts", "store"),
    "intent": SUBSTRATE,
    "evidence": (*SUBSTRATE, "intent", "stations"),
    "decisions": SUBSTRATE,
    "memory": (*SUBSTRATE, "intent"),
    "stations": SUBSTRATE,
    "change": (*SUBSTRATE, "intent", "evidence", "decisions"),
    "work": (*SUBSTRATE, "intent", "evidence", "decisions", "stations", "memory"),
    "delivery": (*SUBSTRATE, "evidence", "decisions"),
    "surface": (
        *SUBSTRATE,
        "intent",
        "evidence",
        "decisions",
        "memory",
        "stations",
        "change",
        "work",
        "delivery",
    ),
    # The SDK is a curated facade over contracts and the platform registries.
    "sdk": ("contracts", "platform"),
}

# The composition root wires every module; nothing imports it.
ROOT_MODULES = ("app", "__main__")


def _forbidden_for(module: str) -> list[str]:
    allowed = set(MODULE_MAP[module]) | {module}
    return [f"{KERNEL}.{m}" for m in MODULE_MAP if m not in allowed] + [
        f"{KERNEL}.{r}" for r in ROOT_MODULES
    ]


def render() -> str:
    """The `.importlinter` configuration implied by the module map."""
    root_packages = "\n".join(f"    {p}" for p in (KERNEL, *FACTORIES, RUNNER))
    out = [
        "# Generated by `python -m scripts.ff.module_map`; do not edit by hand.",
        "# FF-01 import boundaries: the module map, I-18 and the factory SDK rule.",
        "[importlinter]",
        f"root_packages =\n{root_packages}",
        "include_external_packages = False",
        "",
    ]

    def contract(cid: str, name: str, sources: list[str], forbidden: list[str]) -> None:
        src = "\n".join(f"    {s}" for s in sources)
        fbd = "\n".join(f"    {f}" for f in forbidden)
        out.extend(
            [
                f"[importlinter:contract:{cid}]",
                f"name = {name}",
                "type = forbidden",
                f"source_modules =\n{src}",
                f"forbidden_modules =\n{fbd}",
                "",
            ]
        )

    for module in MODULE_MAP:
        contract(
            f"module-{module}",
            f"Module map: {KERNEL}.{module} imports only what the module map allows",
            [f"{KERNEL}.{module}"],
            _forbidden_for(module),
        )
    contract(
        "kernel-never-imports-factories",
        "I-18: the kernel never imports a factory",
        [KERNEL],
        list(FACTORIES),
    )
    contract(
        "factories-use-only-the-sdk",
        "Factories import only grindstone.sdk",
        list(FACTORIES),
        [f"{KERNEL}.{m}" for m in MODULE_MAP if m != "sdk"]
        + [f"{KERNEL}.{r}" for r in ROOT_MODULES],
    )
    contract(
        "runner-is-standalone",
        "The runner shares no code with the control plane or factories",
        [RUNNER],
        [KERNEL, *FACTORIES],
    )
    srcs = "\n".join(f"    {f}" for f in FACTORIES)
    out.extend(
        [
            "[importlinter:contract:factories-independent]",
            "name = Factories never import each other (they meet through interface items)",
            "type = independence",
            f"modules =\n{srcs}",
            "",
        ]
    )
    return "\n".join(out)


if __name__ == "__main__":
    print(render(), end="")
